export function generateScriptMd(project: Project): string {
  let md = `---
title: "${project.title}"
look: "${project.look}"
music: "${project.musicTrack}"
voiceRate: ${project.voiceRate}
voicePitch: ${project.voicePitch}
autoDuck: ${project.autoDuck}
---\n\n`;

  project.scenes.forEach((scene, idx) => {
    md += `## Scene ${idx + 1}: ${scene.title}\n\n`;
    md += `${scene.narration}\n\n`;
    if (scene.elements.length > 0) {
      md += `<!-- Visual Elements Anchors:\n`;
      scene.elements.forEach((el) => {
        md += `  - [${el.type}] "${el.label || el.type}" triggers on word: "${el.triggerWord || 'start'}"\n`;
      });
      md += `-->\n\n`;
    }
  });

  return md;
}

export function generateScenesJs(project: Project): string {
  let js = `// Generated by Explainroo UI (No-Code Visual Builder)
// Compatible with Explainroo CLI specifications: node bin/explainroo.js render

export const config = {
  width: 1280,
  height: 720,
  fps: 30,
  look: '${project.look}',
  music: '${project.musicTrack}',
};

export const scenes = [\n`;

  project.scenes.forEach((scene, sIdx) => {
    js += `  {\n`;
    js += `    id: '${scene.id}',\n`;
    js += `    title: '${scene.title.replace(/'/g, "\\'")}',\n`;
    js += `    durationSeconds: ${scene.durationSeconds},\n`;
    js += `    elements: [\n`;

    scene.elements.forEach((el) => {
      js += `      {\n`;
      js += `        id: '${el.id}',\n`;
      js += `        type: '${el.type}',\n`;
      js += `        x: ${el.x},\n`;
      js += `        y: ${el.y},\n`;
      js += `        width: ${el.width},\n`;
      js += `        height: ${el.height},\n`;
      js += `        label: '${(el.label || '').replace(/'/g, "\\'")}',\n`;
      js += `        color: '${el.color}',\n`;
      js += `        animation: '${el.animation}',\n`;
      js += `        triggerWord: '${el.triggerWord || ''}',\n`;
      js += `        triggerTimeSec: ${el.triggerTimeSec || 0},\n`;
      js += `      },\n`;
    });

    js += `    ],\n`;
    js += `    draw(ctx, rc, t) {\n`;
    js += `      // Custom render callback for Explainroo CLI headless renderer\n`;
    js += `      // Coordinates correspond to 1280x720 canvas canvas\n`;
    js += `    }\n`;
    js += `  }${sIdx < project.scenes.length - 1 ? ',' : ''}\n`;
  });

  js += `];\n\nexport default scenes;\n`;
  return js;
}

export function generateConfigJson(project: Project): string {
  return JSON.stringify(
    {
      name: project.title,
      version: '1.0.0',
      description: project.description,
      engine: 'explainroo-v2',
      render: {
        width: 1280,
        height: 720,
        fps: 30,
        look: project.look,
        autoDucking: project.autoDuck,
        backgroundMusic: project.musicTrack,
      },
    },
    null,
    2
  );
}

